import { formatBDT, formatDate } from './format';

export function downloadFile(filename, content, type = 'text/html') {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const a = Object.assign(document.createElement('a'), { href: url, download: filename });
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

// Generates a printable HTML invoice (open in browser → Print → Save as PDF).
export function downloadInvoice(inv, patient, clinic) {
  const total = inv.items.reduce((s, i) => s + i.amount, 0);
  const rows = inv.items.map((i) => `<tr><td>${i.label}</td><td style="text-align:right">${formatBDT(i.amount)}</td></tr>`).join('');
  downloadFile(
    `${inv.id}.html`,
    `<!doctype html><html><head><meta charset="utf-8"><title>${inv.id}</title><style>body{font-family:Inter,Arial,sans-serif;color:#172238;max-width:680px;margin:40px auto;padding:0 20px}h1{color:#1460d4}table{width:100%;border-collapse:collapse;margin-top:24px}td,th{padding:10px;border-bottom:1px solid #e3e9f3;text-align:left}.t{font-weight:700;font-size:18px}</style></head><body>
<h1>${clinic.clinicName}</h1><p>${clinic.address}<br>${clinic.phone} · ${clinic.email}</p><hr>
<h2>Invoice ${inv.id}</h2><p>Date: ${formatDate(inv.date)}<br>Patient: ${patient.name}<br>Status: ${inv.paid ? 'PAID' : 'UNPAID'}</p>
<table><thead><tr><th>Description</th><th style="text-align:right">Amount</th></tr></thead><tbody>${rows}<tr><td class="t">Total</td><td class="t" style="text-align:right">${formatBDT(total)}</td></tr></tbody></table>
<p style="margin-top:40px;color:#6a7c9e;font-size:12px">Demo invoice generated by the SmileCare frontend.</p></body></html>`
  );
}

export function downloadPrescription(rx, clinic) {
  const rows = rx.items.map((i) => `<tr><td>${i.name}</td><td>${i.dosage || ''}</td><td>${i.duration || ''}</td></tr>`).join('');
  downloadFile(
    `prescription-${rx.id}.html`,
    `<!doctype html><html><head><meta charset="utf-8"><title>Prescription ${rx.id}</title><style>body{font-family:Inter,Arial,sans-serif;color:#172238;max-width:680px;margin:40px auto;padding:0 20px}h1{color:#1460d4;margin:0}table{width:100%;border-collapse:collapse;margin-top:12px}td,th{padding:8px;border-bottom:1px solid #e3e9f3;text-align:left}.rx{font-size:32px;color:#0b96aa;font-weight:800}</style></head><body>
<h1>${clinic.clinicName}</h1><p>${clinic.address} | ${clinic.phone}</p><hr>
<p><strong>${rx.dentist || ''}</strong><br>Date: ${formatDate(rx.date)}</p>
<p>Patient: <strong>${rx.patientName || ''}</strong></p>
<p>Diagnosis: ${rx.diagnosis || '-'}</p>
<div class="rx">Rx</div>
<table><thead><tr><th>Medicine</th><th>Dosage</th><th>Duration</th></tr></thead><tbody>${rows}</tbody></table>
${rx.notes ? `<p><strong>Advice:</strong> ${rx.notes}</p>` : ''}${rx.followUp ? `<p><strong>Follow-up:</strong> ${formatDate(rx.followUp)}</p>` : ''}
<p style="margin-top:60px">______________________<br>Signature</p></body></html>`
  );
}
